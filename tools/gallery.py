src, out = sys.argv[1], sys.argv[2]
cards = []
for name, title, text in SHOTS:
    im = Image.open(f"{src}/{name}.ppm").convert("RGB")
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    b = base64.b64encode(buf.getvalue()).decode()
    cards.append(f'<figure><img src="data:image/png;base64,{b}" width="240" height="135" alt="{html.escape(title)}">'
                 f'<figcaption><b>{html.escape(title)}</b><span>{html.escape(text)}</span></figcaption></figure>')

page = open("web/gallery.src.html", encoding="utf-8").read().replace("__CARDS__", "\n".join(cards))
open(out, "w", encoding="utf-8").write(page)
print(out, len(page))
